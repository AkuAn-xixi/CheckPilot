const getPreferredLocale = () => {
  if (typeof window === 'undefined') {
    return DEFAULT_LOCALE
  }

  const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY)
  if (stored === DEFAULT_LOCALE || stored === ALTERNATE_LOCALE) {
    return stored
  }

  return navigator.language?.toLowerCase().startsWith('zh') ? DEFAULT_LOCALE : ALTERNATE_LOCALE
}

const setDocumentLanguage = (locale) => {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale
  }
}

const initialLocale = getPreferredLocale()

export const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: initialLocale,
  fallbackLocale: DEFAULT_LOCALE,
  messages
})

export const setLocale = (locale) => {
  const normalized = locale === ALTERNATE_LOCALE ? ALTERNATE_LOCALE : DEFAULT_LOCALE
  i18n.global.locale.value = normalized

  if (typeof window !== 'undefined') {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, normalized)
  }

  setDocumentLanguage(normalized)
}

setDocumentLanguage(initialLocale)